    SUBJECT = '<PASTE THE sub VALUE FROM THE FIRST RUN>'
    OIDC_AUDIENCE_LIST = ('<SAME VALUE AS YOUR SNOWFLAKE_AUDIENCE VARIABLE>')
  );
  
GRANT ROLE SVC_OPERATIONS_ROLE TO USER SVC_OPERATIONS_USER;
